"""Golden values for the browser forward model (``frontend/src/lib/km.ts``).

``paintmixer parity-fixture`` writes ``frontend/src/lib/km.parity.json``; the backend test
``test_parity_fixture_is_current`` fails when it is stale and the frontend's Vitest suite checks
the TypeScript implementation against it. Everything comes from the Python implementation, so
the two cannot drift apart silently.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np

from paintmixer.colorsci.convert import (
    _M_XYZ_TO_RGB,
    SRGB_WHITE,
    lab_to_srgb,
    reflectance_to_lab,
    srgb_to_hex,
)
from paintmixer.colorsci.delta_e import delta_e_2000
from paintmixer.colorsci.illuminants import SERIES as ILLUMINANT_SERIES
from paintmixer.colorsci.km import KMModel
from paintmixer.colorsci.spectral import WAVELENGTHS, Illuminant, weighting_matrix, white_point
from paintmixer.solver.multimix import grid_parts, multimix, simplex_lattice
from paintmixer.solver.ramp import ramp, ramp_fractions

REPORTED = (Illuminant.D65, Illuminant.A, Illuminant.F11)
FIXTURE = Path(__file__).resolve().parents[3] / "frontend" / "src" / "lib" / "km.parity.json"


def _r(a: Any, digits: int = 12) -> Any:
    return np.round(np.asarray(a, dtype=np.float64), digits).tolist()


def colorimetry() -> dict[str, Any]:
    """Tables a client needs to turn reflectance into XYZ, Lab and sRGB like the backend."""
    return {
        "wavelengths": WAVELENGTHS.tolist(),
        "illuminants": {
            ill.value: {"weights": _r(weighting_matrix(ill)), "white": _r(white_point(ill))}
            for ill in REPORTED
        },
        "srgb": {"white": _r(SRGB_WHITE), "xyz_to_rgb": _r(_M_XYZ_TO_RGB)},
    }


def build_fixture() -> dict[str, Any]:
    from paintmixer.calibration.synthetic import STARTER_IDS, synthetic_paints

    ps = synthetic_paints(STARTER_IDS)
    km = KMModel(np.stack([p.K for p in ps]), np.stack([p.S for p in ps]), 0.0, 0.5)
    ids = list(STARTER_IDS)
    rng = np.random.default_rng(2026)
    mixtures = [np.eye(len(ids))[i] for i in range(len(ids))]
    for _ in range(12):
        k = int(rng.integers(2, 5))
        c = np.zeros(len(ids))
        c[rng.choice(len(ids), k, replace=False)] = rng.dirichlet(np.ones(k))
        mixtures.append(c)
    target = np.array([55.0, -12.0, -25.0])
    cases = []
    for c in mixtures:
        R = km.reflectance(c)
        lab = {ill.value: _r(reflectance_to_lab(R, ill)) for ill in REPORTED}
        srgb = lab_to_srgb(reflectance_to_lab(R))
        cases.append(
            {
                "fractions": dict(zip(ids, _r(c), strict=True)),
                "reflectance": _r(R),
                "lab": lab,
                "hex": srgb_to_hex(srgb.rgb),
                "out_of_gamut": bool(srgb.out_of_gamut),
                "de2000_to_target": float(delta_e_2000(reflectance_to_lab(R), target)),
            }
        )
    rng2 = np.random.default_rng(7)
    gamut_labs = np.column_stack([rng2.uniform(15, 95, 40), rng2.uniform(-120, 120, (40, 2))])
    gm = lab_to_srgb(gamut_labs)
    tint = ramp(km, ids.index("phthalo-blue"), 0, ramp_fractions(6, "log", 0.02))
    mm_ids = ["titanium-white", "phthalo-blue", "arylide-yellow"]
    mm_idx = [ids.index(p) for p in mm_ids]
    lattice = simplex_lattice(3, 4)
    lat_cells = multimix(km, mm_idx, lattice)
    levels = [[0.0, 4.0, 8.0], [0.0, 1.0], [0.0, 1.0, 2.0]]
    g_shape, g_parts = grid_parts(levels)
    grid_cells = multimix(km, mm_idx, g_parts)
    return {
        "_comment": "Generated by `uv run paintmixer parity-fixture`; do not edit by hand.",
        "multimix": {
            "paints": mm_ids,
            "simplex": {
                "divisions": 4,
                "parts": lattice.tolist(),
                "hex": [c.hex for c in lat_cells],
                "xy": [_r(c.xy) for c in lat_cells],
            },
            "grid": {
                "levels": levels,
                "shape": list(g_shape),
                "parts": g_parts.tolist(),
                "hex": [c.hex for c in grid_cells],
            },
        },
        "colorimetry": colorimetry(),
        "model": {
            "paint_ids": ids,
            "K": _r(km.K),
            "S": _r(km.S),
            "k1": km.k1,
            "k2": km.k2,
        },
        "target_lab": target.tolist(),
        "cases": cases,
        "gamut_map": [
            {"lab": _r(lab), "hex": srgb_to_hex(rgb), "out_of_gamut": bool(o)}
            for lab, rgb, o in zip(gamut_labs, gm.rgb, gm.out_of_gamut, strict=True)
        ],
        # GET /illuminants, which the frontend's built-in fallback (lib/colour.ts SERIES) mirrors
        "illuminants": [
            {
                "id": sr.id,
                "name": sr.name,
                "description": sr.description,
                "default": sr.default.value,
                "members": [{"code": mm.code.value, "cct": mm.cct} for mm in sr.members],
            }
            for sr in ILLUMINANT_SERIES
        ],
        "ramp": {
            "paint_a": "phthalo-blue",
            "paint_b": "titanium-white",
            "fractions": _r(ramp_fractions(6, "log", 0.02)),
            "hex": [s.hex for s in tint],
            "lab": [_r(s.lab) for s in tint],
        },
    }


def fixture_json() -> str:
    return json.dumps(build_fixture(), indent=1) + "\n"
